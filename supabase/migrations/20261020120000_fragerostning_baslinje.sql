-- Baslinje för röstningen på Tvåkommanollans egna MEK-uppgifter.
--
-- Röstningen (20261019120000_fragerostning.sql) startar varje fråga på noll,
-- och med få röstande står nästan alla egna uppgifter på noll länge. En
-- genomläsning av alla 550 gav varje uppgift 0–5 tummar upp efter hur bra den
-- är (ett entydigt svar, distraktorer som lockar men faller, en text som
-- inte avslöjar svaret). Fördelningen är medvetet normalfördelad kring 3:
-- 31 st 1, 73 st 2, 324 st 3, 97 st 4 och 25 st 5. Betygen står också i
-- scripts/mek-gen/baslinje-betyg.json.
--
-- Egen tabell och inte rader i question_votes: en röst där kräver ett konto,
-- och baslinjen ska gå att se, ändra och ta bort för sig. Vyn räknar in den
-- som fullviktiga upp-röster, så både siffrorna bredvid tummarna och urvalet
-- (question-votes.ts) ser den utan kodändring.
--
-- Bara uppgifter som ännu saknar röster får en baslinje (vid körningen hade 7
-- av 550 redan riktiga röster). Kör om utan risk: befintliga rader rörs inte.
CREATE TABLE IF NOT EXISTS public.question_vote_baseline (
  question_id uuid PRIMARY KEY REFERENCES public.questions (id) ON DELETE CASCADE,
  up smallint NOT NULL CHECK (up BETWEEN 0 AND 5),
  created_at timestamptz NOT NULL DEFAULT now()
);

-- Ingen policy: läses bara via vyn med service role, precis som question_votes.
ALTER TABLE public.question_vote_baseline ENABLE ROW LEVEL SECURITY;

CREATE OR REPLACE VIEW public.question_vote_stats
WITH (security_invoker = true) AS
WITH votes AS (
  SELECT
    question_id,
    count(*) FILTER (WHERE vote = 1 AND NOT is_guest)::int AS up,
    count(*) FILTER (WHERE vote = -1 AND NOT is_guest)::int AS down,
    count(*) FILTER (WHERE vote = 1 AND is_guest)::int AS guest_up,
    count(*) FILTER (WHERE vote = -1 AND is_guest)::int AS guest_down
  FROM public.question_votes
  GROUP BY question_id
)
SELECT
  coalesce(v.question_id, b.question_id) AS question_id,
  (coalesce(v.up, 0) + coalesce(b.up, 0))::int AS up,
  coalesce(v.down, 0)::int AS down,
  coalesce(v.guest_up, 0)::int AS guest_up,
  coalesce(v.guest_down, 0)::int AS guest_down
FROM votes v
FULL OUTER JOIN public.question_vote_baseline b ON b.question_id = v.question_id;

